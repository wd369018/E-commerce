def rel_check(
    label: str,
    child_df: pd.DataFrame,
    child_col: str,
    parent_df: pd.DataFrame,
    parent_col: str,
    child_name: str,
    parent_name: str,
) -> dict:
    child_vals = child_df[child_col].dropna()
    parent_vals = set(parent_df[parent_col].dropna())
    orphan = int((~child_vals.isin(parent_vals)).sum())
    child_rows = len(child_df)
    distinct_child = child_vals.nunique()
    rows_per_parent = child_rows / distinct_child if distinct_child else 0
    cardinality = "1:1" if child_rows == distinct_child else f"1:{child_rows / max(distinct_child,1):.2f} (avg)"
    res = {
        "relationship": f"{parent_name}.{parent_col} -> {child_name}.{child_col}",
        "child_rows": child_rows,
        "distinct_parents_used": int(distinct_child),
        "orphans": orphan,
        "avg_rows_per_parent": round(rows_per_parent, 3),
        "cardinality": cardinality,
    }
    c(
        f"{label:38s} child_rows={child_rows:>8,} distinct_parents={distinct_child:>8,} "
        f"orphans={orphan:>7,} avg_rows/parent={rows_per_parent:.3f}"
    )
    return res


